"""Write the intake bundle the Find care page reads before it looks for a campus.

    python -m app.storm_ui.build_intake            write app/storm_ui/data/intake.js
    python -m app.storm_ui.build_intake --check    fail if the committed file is out of date

The page never decides anything about a patient. This build step asks the team's intake engine
(`app.intake.assess_intake`) about every state a visitor can reach, for each fictional story, and
stores the engine's answers unedited. Where a story's care summary can be confirmed, it takes a
real confirmation from `confirm_intake`, stores the ready answer that follows, and stores the campus
answer `app.intake.finder_bridge.find_care_for_intake` gives for that same input, story and
confirmation from each starting point. The page looks these records up and shows them.

Who owns what the page shows:
    states, concerns, intake reasons      app.intake.assessment     assessment_catalogue()
    warning rules, messages, sources      app.intake.danger_signs   warning/message/source_catalogue()
    referral reasons, authority labels    app.intake.referral_gate  referral_catalogue()
    questions and answer labels           app.intake.questions      question_catalogue()
    the seven stories                     tests/intake/scenarios/journeys.json (pinned by digest.json;
                                          the engine admits only the reviewed editions listed in
                                          contracts/intake/reviewed_scenarios.json)
    campus answers                        app.intake.finder_bridge  find_care_for_intake()
This module adds only the short picker name of each story and reuses the Find care page's names
for services and urgencies. The build stops if a stored answer names an ID with no display entry.

Everything here is invented. No patient, symptom report or clinician is real, and the rules are a
demonstration that no clinician has validated.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from app.intake import (POLICY_VERSION, SCENARIO_SCHEMA_VERSION, SCHEMA_VERSION, assess_intake,
                        assessment_catalogue, confirm_intake)
from app.intake.danger_signs import message_catalogue, source_catalogue, warning_catalogue
from app.intake.finder_bridge import ORIGIN_IDS, find_care_for_intake
from app.intake.questions import question_catalogue
from app.intake.referral_gate import referral_catalogue
from app.storm_ui import build_ask

ROOT = Path(__file__).resolve().parents[2]
TARGET = Path(__file__).resolve().parent / "data" / "intake.js"
STORIES = ROOT / "tests" / "intake" / "scenarios" / "journeys.json"
DIGEST = STORIES.with_name("digest.json")
REVIEWED = ROOT / "contracts" / "intake" / "reviewed_scenarios.json"
HEADER = ("// Generated by `python -m app.storm_ui.build_intake`. Do not edit by hand.\n"
          "// Synthetic: fictional stories, unedited answers from app.intake, no clinical validation.\n")

# The page is opened from a file, so the whole walk travels with it. Past this it needs a review.
MAX_STATES = 5000

# Picker names, in the order the page lists the stories. The story text itself is the story's own
# `presenting_problem`. A story without a name here, or a name without a story, stops the build.
STORY_NAMES = [
    ("scheduled_dialysis", "Scheduled dialysis session"),
    ("scheduled_mri", "Scheduled MRI scan"),
    ("injury_unassessed", "A fall, not yet assessed"),
    ("injury_assessed", "The same fall, after an assessment"),
    ("warning_with_mri_plan", "MRI referral, with new chest pain"),
    ("incomplete_history", "MRI referral, history incomplete"),
    ("unsupported_concern", "General health concern"),
]
PLAN_FIELDS = ("authority", "service", "urgency", "required_capabilities", "preferred_capabilities")


class BuildError(ValueError):
    """The engine, the stories and the page disagree. Nothing is written."""


def stories() -> dict:
    """The trusted story editions, after checking the file against its pinned digest."""
    raw = STORIES.read_bytes()
    pinned = json.loads(DIGEST.read_text(encoding="utf-8"))["sha256"]
    if hashlib.sha256(raw).hexdigest() != pinned:
        raise BuildError(f"{STORIES.name} does not match the digest pinned in {DIGEST.name}")
    fixture = json.loads(raw)
    if fixture.get("synthetic") is not True:
        raise BuildError("The story file is not marked synthetic")
    found = fixture["scenarios"]
    if sorted(found) != sorted(story_id for story_id, _ in STORY_NAMES):
        raise BuildError("The story file and the page's story names list different stories")
    for story_id, story in found.items():
        if story["scenario_id"] != story_id or story["schema_version"] != SCENARIO_SCHEMA_VERSION:
            raise BuildError(f"Story {story_id} is not a {SCENARIO_SCHEMA_VERSION} edition of itself")
    return found


def _merge(*sections: dict) -> dict:
    out = {}
    for section in sections:
        for name, value in section.items():
            if name in out and out[name] != value:
                raise BuildError(f"Two owners give different display entries for {name}")
            out[name] = value
    return out


def catalogue() -> dict:
    """Every display entry the page may use, from the module that owns it."""
    engine, referral = assessment_catalogue(), referral_catalogue()
    return {
        "messages": _merge(engine["messages"], message_catalogue()),
        # A warning stop gives its message ID as its reason too, so those entries serve both.
        "reasons": _merge(engine["reasons"], referral["reasons"], message_catalogue()),
        "concerns": engine["concerns"],
        "authorities": referral["authorities"],
        "rules": warning_catalogue(),
        "sources": _merge(source_catalogue(), engine["sources"]),
        "service_names": dict(build_ask.SERVICES),
        "urgency_names": {urgency: name for urgency, name, _ in build_ask.URGENCIES},
    }


def payload(story_id: str, answers: list) -> dict:
    """What the engine is asked. The revision is the number of answers the visitor has given."""
    return {"schema_version": SCHEMA_VERSION, "mode": "synthetic", "scenario_id": story_id,
            "input_revision": len(answers), "answers": dict(answers)}


def key(story_id: str, answers: list, confirmed: bool = False) -> str:
    """Where one state is stored: the story, the visitor's answers in the order they were asked."""
    return (story_id + "|" + ",".join(f"{question}={answer}" for question, answer in answers)
            + ("|confirmed" if confirmed else ""))


def _campus_answers(story: dict, answers: list, receipt, ready: dict, direct: dict) -> dict:
    """The bridge's answer from every starting point, for one confirmed input."""
    request, found = ready["request"], {}
    for origin in ORIGIN_IDS:
        produced = find_care_for_intake(payload(story["scenario_id"], answers), scenario=story,
                                        confirmation=receipt, origin_id=origin)
        if produced["assessment"] != ready or produced["finder"] is None:
            raise BuildError(f"The bridge and the engine disagree on {key(story['scenario_id'], answers, True)}")
        response = build_ask.stable(produced["finder"])
        # The page explains a campus answer with the Find care page's own record of that request.
        # If the two ever differ (a required capability, say), the page could not explain what it
        # shows, so the build stops here instead.
        same = direct["answers"].get(build_ask.key(request["service"], origin, request["urgency"]))
        if same is None or build_ask.stable(same["response"]) != response:
            raise BuildError(f"The bridge's answer from {origin} differs from the Find care page's answer")
        found[origin] = response
    return found


def walk(story: dict, questions: dict, direct: dict) -> tuple:
    """Every state a visitor can reach in one story, the campus answers, and the longest path."""
    story_id = story["scenario_id"]
    states, campuses, longest = {}, {}, 0
    pending = [[]]
    while pending:
        answers = pending.pop()
        longest = max(longest, len(answers))
        result = assess_intake(payload(story_id, answers), scenario=story)
        if result["state"] == "invalid_input":
            # The engine refuses a story that is not a reviewed edition, and anything it cannot read.
            raise BuildError(f"The engine refused {key(story_id, answers)}: {', '.join(result['reason_codes'])}")
        states[key(story_id, answers)] = result
        if result["next_question_ids"]:
            (question,) = result["next_question_ids"]
            if question in dict(answers) or question not in questions:
                raise BuildError(f"The engine asked {question!r}, which the page cannot ask at {key(story_id, answers)}")
            pending.extend(answers + [(question, choice["id"])] for choice in questions[question]["answers"])
        elif result["state"] == "confirmation_required":
            receipt = confirm_intake(payload(story_id, answers), scenario=story)
            ready = assess_intake(payload(story_id, answers), scenario=story, confirmation=receipt)
            if ready["state"] != "ready" or ready["input_fingerprint"] != result["input_fingerprint"]:
                raise BuildError(f"A real confirmation did not make {key(story_id, answers)} ready")
            states[key(story_id, answers, True)] = ready
            campuses[key(story_id, answers, True)] = _campus_answers(story, answers, receipt, ready, direct)
    return states, campuses, longest


def _missing(made: dict) -> list:
    """Every ID a stored answer or a story names that has no display entry."""
    cat, questions = made["catalogue"], {row["id"]: row for row in made["questions"]}
    gaps = []

    def need(section: str, name, where: str) -> None:
        table = questions if section == "questions" else cat[section]
        if name not in table:
            gaps.append(f"{where}: no {section} entry for {name!r}")

    for row in made["questions"]:
        for source in row["sources"]:
            need("sources", source, row["id"])
    for rule in cat["rules"].values():
        need("questions", rule["question_id"], "warning rule")
        for source in rule["source_ids"]:
            need("sources", source, "warning rule")
    for story in made["scenarios"]:
        for fact in story["known"]:
            need("questions", fact["id"], story["id"])
            labels = [choice["id"] for choice in questions.get(fact["id"], {"answers": []})["answers"]]
            if fact["answer"] not in labels:
                gaps.append(f"{story['id']}: no answer label for {fact['id']}={fact['answer']}")
        if story["plan"]:
            need("authorities", story["plan"]["authority"], story["id"])
            need("service_names", story["plan"]["service"], story["id"])
            need("urgency_names", story["plan"]["urgency"], story["id"])
    for where, a in made["assessments"].items():
        for name in a["message_ids"]:
            need("messages", name, where)
        for name in a["reason_codes"]:
            need("reasons", name, where)
        for name in a["rule_ids"]:
            need("rules", name, where)
        for name in a["source_ids"]:
            need("sources", name, where)
        for name in [*a["unknowns"], *a["next_question_ids"]]:
            need("questions", name, where)
        for concern in a["concerns"]:
            need("concerns", concern["category"], where)
            need("reasons", concern["reason_code"], where)
            for source in concern["source_ids"]:
                need("sources", source, where)
        for part in (a["care_summary"], a["request"]):
            if part:
                need("service_names", part["service"], where)
                need("urgency_names", part["urgency"], where)
        if a["care_summary"]:
            need("authorities", a["care_summary"]["authority"], where)
    return gaps


def bundle() -> dict:
    found, questions = stories(), question_catalogue()
    by_id = {row["id"]: row for row in questions}
    direct = build_ask.bundle()
    if tuple(place["id"] for place in direct["places"]) != tuple(ORIGIN_IDS):
        raise BuildError("The bridge and the Find care page list different starting points")
    assessments, campuses, longest, listed = {}, {}, 0, []
    for story_id, name in STORY_NAMES:
        story = found[story_id]
        states, answers, depth = walk(story, by_id, direct)
        assessments.update(states)
        campuses.update(answers)
        longest = max(longest, depth)
        plan = story["clinician_plan"]
        listed.append({
            "id": story_id, "version": story["scenario_version"], "name": name,
            "story": story["presenting_problem"],
            # What the story already states, in the order the questions would be asked.
            "known": [{"id": row["id"], "answer": story["known_answers"][row["id"]]}
                      for row in questions if row["id"] in story["known_answers"]],
            "plan": {field: plan[field] for field in PLAN_FIELDS} if plan else None,
        })
    made = {
        "synthetic": True,
        "schema_version": SCHEMA_VERSION, "policy_version": POLICY_VERSION,
        "scenario_schema_version": SCENARIO_SCHEMA_VERSION,
        # Which rule set, stories and campus fixture these stored answers pair.
        "pairing": {
            "policy_version": POLICY_VERSION,
            "stories_sha256": hashlib.sha256(STORIES.read_bytes()).hexdigest(),
            "reviewed_editions_sha256": hashlib.sha256(REVIEWED.read_bytes()).hexdigest(),
            "finder_fixture_sha256": hashlib.sha256(build_ask.FIXTURE.read_bytes()).hexdigest(),
            "finder_as_of": build_ask.AS_OF,
        },
        "longest_path": longest,
        "origins": list(ORIGIN_IDS),
        "questions": questions,
        "scenarios": listed,
        "catalogue": catalogue(),
        "assessments": dict(sorted(assessments.items())),
        "finder": dict(sorted(campuses.items())),
    }
    gaps = _missing(made)
    if gaps:
        raise BuildError("Display entries are missing:\n  " + "\n  ".join(gaps[:20]))
    if len(made["assessments"]) > MAX_STATES:
        raise BuildError(f"{len(made['assessments'])} states is more than the {MAX_STATES} the page bundle "
                         "accepts. Report the count for review before releasing the page.")
    return made


def measure(made: dict) -> dict:
    """The numbers the integration receipt reports."""
    states = made["assessments"].values()
    counts = {}
    for a in states:
        counts[a["state"]] = counts.get(a["state"], 0) + 1
    return {"states": len(made["assessments"]), "by_state": dict(sorted(counts.items())),
            "ready": counts.get("ready", 0), "longest_path": made["longest_path"],
            "campus_answers": sum(len(by_origin) for by_origin in made["finder"].values())}


def render() -> str:
    body = json.dumps(bundle(), ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    return f"{HEADER}window.CARE_INTAKE = {body};\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.storm_ui.build_intake", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Compare with the committed file and change nothing")
    args = parser.parse_args(argv)
    try:
        text = render()
    except BuildError as error:
        print(f"NOT BUILT: {error}", file=sys.stderr)
        return 1
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"OUT OF DATE: {TARGET}", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({len(text.encode('utf-8'))} bytes) {json.dumps(measure(bundle()))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
