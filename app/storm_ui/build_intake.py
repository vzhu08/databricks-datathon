def revision(scenario_id: str, answers: list) -> str:
    """A short fingerprint of exactly what was answered. A confirmation is bound to one of these."""
    text = json.dumps([POLICY_VERSION, scenario_id, list(answers)], separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def assess(scenario: dict, answers: list, confirmed_revision: str | None = None) -> dict:
    """PROVISIONAL stand-in for the team's assessment engine. Deterministic: no clock, no network.

    `answers` are the answers so far, in question order. `confirmed_revision` is the revision a
    visitor confirmed, if any; it counts only when it equals the revision of these answers.
    """
    if any(answer not in ANSWERS for answer in answers) or len(answers) > MAX_QUESTIONS:
        raise ValueError("answers must be yes, no or unknown, at most one per question")
    given = dict(zip((q["id"] for q in QUESTIONS), answers))
    clinician = scenario.get("clinician")
    out = {
        "schema_version": SCHEMA_VERSION, "policy_version": POLICY_VERSION, "synthetic": True,
        "scenario_id": scenario["id"], "input_revision": revision(scenario["id"], answers),
        "state": "more_information", "message_id": "in_progress", "next_question_id": None,
        "concerns": [], "reason_ids": [], "source_ids": [], "limit_ids": ["placeholder_rules"],
        "unknown_question_ids": [qid for qid, answer in given.items() if answer == "unknown"],
        "clinician": clinician,
        "confirmation": {"required": False, "present": False, "bound_to": None},
        "request": None,
    }

    # 1. A known danger sign wins over everything else, including unanswered questions.
    yes = [qid for qid in DANGER if given.get(qid) == "yes"]
    if yes:
        reasons = [f"danger_yes.{qid}" for qid in yes]
        if clinician:
            reasons.append("existing_request_set_aside")
        sources = sorted({s for q in QUESTIONS if q["id"] in yes for s in q["sources"]} | {"india-112"})
        out.update(state="escalation", message_id="escalation", reason_ids=reasons, source_ids=sources,
                   concerns=["possible_emergency"], limit_ids=["not_a_diagnosis", "placeholder_rules"])
        return out

    # 2. Ask each safety question. Unknown is never read as no.
    for qid in DANGER:
        if qid not in given:
            out["next_question_id"] = qid
            return out
    if any(given[qid] == "unknown" for qid in DANGER):
        out.update(message_id="safety_unresolved", limit_ids=["unknown_is_not_no", "placeholder_rules"])
        return out

    # 3. Who the demonstration covers.
    if SCOPE not in given:
        out["next_question_id"] = SCOPE
        out["reason_ids"] = ["no_danger_reported"]
        return out
    if given[SCOPE] == "unknown":
        out.update(message_id="scope_unresolved", reason_ids=["no_danger_reported"],
                   limit_ids=["unknown_is_not_no", "placeholder_rules"])
        return out
    safe_limits = ["no_danger_is_not_safe", "placeholder_rules"]
    if given[SCOPE] == "no":
        out.update(state="unsupported", message_id="unsupported_population", reason_ids=["child_or_pregnant"],
                   limit_ids=safe_limits)
        return out

    # 4. Only a clinician in the story can ask for a service.
    if not clinician:
        out.update(state="assessment_needed", message_id="assessment_needed",
                   concerns=[scenario["concern"]], source_ids=["referral-first"],
                   reason_ids=["no_danger_reported", "no_clinician_request", "symptoms_do_not_order_service"],
                   limit_ids=["not_a_diagnosis"] + safe_limits)
        return out
    if clinician["service"] not in SUPPORTED_SERVICES:
        out.update(state="unsupported", message_id="unsupported_need",
                   reason_ids=["no_danger_reported", "service_not_modelled"], limit_ids=safe_limits)
        return out

    # 5. The visitor confirms the summary for exactly these answers. Then, and only then, a request exists.
    reasons = ["no_danger_reported", f"clinician.{clinician['kind']}"]
    out["confirmation"]["required"] = True
    if confirmed_revision != out["input_revision"]:
        out.update(state="awaiting_confirmation", message_id="awaiting_confirmation", reason_ids=reasons,
                   limit_ids=safe_limits)
        return out
    out["confirmation"].update(present=True, bound_to=out["input_revision"])
    out.update(state="ready", message_id="ready", reason_ids=reasons + ["confirmed"],
               limit_ids=safe_limits + ["availability_unknown"],
               request={"service": clinician["service"], "urgency": clinician["urgency"],
                        "required_capabilities": []})
    return out


def key(scenario_id: str, answers: list, confirmed: bool = False) -> str:
    return scenario_id + "|" + ",".join(answers) + ("|confirmed" if confirmed else "")


def walk(scenario: dict) -> dict:
    """Every state a visitor can reach for one fictional patient, by answering in order."""
    found = {}
    pending = [[]]
    while pending:
        answers = pending.pop()
        result = assess(scenario, answers)
        found[key(scenario["id"], answers)] = result
        if result["next_question_id"]:
            pending.extend(answers + [answer] for answer in ANSWERS)
        elif result["state"] == "awaiting_confirmation":
            found[key(scenario["id"], answers, True)] = assess(scenario, answers, result["input_revision"])
    return found


def bundle() -> dict:
    assessments = {}
    for scenario in SCENARIOS:
        assessments.update(walk(scenario))
    return {
        "synthetic": True, "provisional": True,
        "schema_version": SCHEMA_VERSION, "policy_version": POLICY_VERSION,
        "max_questions": MAX_QUESTIONS, "answers": list(ANSWERS),
        "questions": QUESTIONS,
        "scenarios": [{k: v for k, v in scenario.items() if k != "concern"} for scenario in SCENARIOS],
        "catalogue": CATALOGUE,
        "assessments": dict(sorted(assessments.items())),
    }


def render() -> str:
    body = json.dumps(bundle(), ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    return f"{HEADER}window.CARE_INTAKE = {body};\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.storm_ui.build_intake", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Compare with the committed file and change nothing")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"OUT OF DATE: {TARGET}", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({len(text.encode('utf-8'))} bytes, {len(bundle()['assessments'])} states)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
