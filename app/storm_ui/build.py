"""Embed the synthetic replays the page needs, so it opens from a file with no server.

    python -m app.storm_ui.build            # rewrite app/storm_ui/data/scenarios.js
    python -m app.storm_ui.build --check    # exit 1 when the committed file is out of date

Every replay comes from app.simulation unchanged. Nothing is ranked or allocated here.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from app.simulation.replay import replay
from app.simulation.scenario import SCENARIOS, make_scenario

SEED = 17
DETOUR_CAPS = (0, 5, 10, 15)
DEFAULT = ("storm", 10)
TARGET = Path(__file__).resolve().parent / "data" / "scenarios.js"
HEADER = ("// Generated by `python -m app.storm_ui.build`. Do not edit by hand.\n"
          "// Synthetic: fictional campuses, origins, requests, staffed slots and travel times.\n")


def key(scenario: str, detour: int) -> str:
    return f"{scenario}|{detour}"


def bundle() -> dict:
    replays = {key(name, cap): replay(make_scenario(name, SEED), cap)
               for name in SCENARIOS for cap in DETOUR_CAPS}
    return {"seed": SEED, "scenarios": list(SCENARIOS), "detour_caps": list(DETOUR_CAPS),
            "default": key(*DEFAULT), "replays": replays}


def render() -> str:
    body = json.dumps(bundle(), ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    return f"{HEADER}window.STORM_BUNDLE = {body};\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.storm_ui.build", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Compare with the committed file and change nothing")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"OUT OF DATE: {TARGET}", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({len(text.encode('utf-8'))} bytes, {len(SCENARIOS) * len(DETOUR_CAPS)} replays)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
