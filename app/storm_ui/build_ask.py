"""Work out every answer the Find care page can show, so it opens from a file with no server.

    python -m app.storm_ui.build_ask            # rewrite app/storm_ui/data/answers.js
    python -m app.storm_ui.build_ask --check    # exit 1 when the committed file is out of date

Every ranking, score, weight and reason comes from app.ranking.urgency.rank_campuses unchanged.
This module only supplies the invented inputs: the record text and review decision for each
fictional campus, and the travel minutes of the storm scenario's four starting points. A campus
is a candidate for a service only when its invented record mentions that service.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from app.ranking.urgency import rank_campuses

ROOT = Path(__file__).resolve().parents[2]
TARGET = Path(__file__).resolve().parent / "data" / "answers.js"
FIXTURE = ROOT / "contracts" / "fixtures" / "storm_replay.json"
HEADER = ("// Generated by `python -m app.storm_ui.build_ask`. Do not edit by hand.\n"
          "// Synthetic: fictional campuses, record text, review decisions, starting points and travel times.\n")

AS_OF = "2026-11-21"
DECIMALS = 9
SERVICES = [("dialysis", "Dialysis"), ("mri", "MRI scan"), ("trauma_care", "Trauma care")]
# The travel limit for each urgency is a demo assumption, like the weights inside the ranker.
URGENCIES = [("routine", "Routine", 40), ("time_sensitive", "Time-sensitive", 30), ("highest", "Most urgent", 20)]
PLACES = [("central", "Central point"), ("east", "East point"), ("south", "South point"), ("west", "West point")]
SITE, LIST, AUDIT = "SYNTHETIC-HOSPITAL-SITE", "SYNTHETIC-STATE-LIST", "SYNTHETIC-AUDIT-REPORT"

# campus -> service -> (review decision, date of the statement, independent source families, record text)
RECORDS = {
    "A": {
        "dialysis": ("yes", "2024-03-10", [SITE],
                     "Haemodialysis unit with six stations and bedside heart monitoring."),
        "mri": ("yes", "2026-08-02", [SITE, LIST],
                "MRI scanner in the imaging block, staffed on weekdays."),
    },
    "B": {
        "dialysis": ("yes", "2026-10-28", [SITE, LIST],
                     "Dialysis centre with eight machines, running two shifts a day."),
    },
    "C": {
        "dialysis": ("yes", "2026-06-15", [SITE],
                     "Kidney care ward offers haemodialysis by appointment."),
        "trauma_care": ("unconfirmed", None, [],
                        "Emergency room open 24 hours. Trauma surgery is not mentioned."),
    },
    "D": {
        "mri": ("yes", "2025-11-05", [SITE],
                "MRI and CT scans available in the diagnostics wing."),
    },
    "E": {
        "dialysis": ("unconfirmed", None, [],
                     "Patients who need dialysis are referred to a partner centre."),
        "trauma_care": ("yes", None, [SITE],
                        "Accident and trauma care. The page carries no date."),
    },
    "F": {
        "dialysis": ("yes", "2026-09-12", [SITE, LIST, AUDIT],
                     "Dialysis unit with twelve stations, four of them monitored."),
        "trauma_care": ("yes", "2026-09-12", [SITE, LIST],
                        "Trauma centre with an operating theatre staffed day and night."),
    },
}
EXAMPLES = [
    ("Routine dialysis from the central point", "dialysis", "central", "routine"),
    ("The same patient, now most urgent", "dialysis", "central", "highest"),
    ("Urgent trauma care with weak evidence", "trauma_care", "central", "highest"),
]


def key(service: str, place: str, urgency: str) -> str:
    return f"{service}|{place}|{urgency}"


def _candidates(service: str, travel: dict) -> list:
    rows = []
    for campus, records in RECORDS.items():
        if service not in records:
            continue
        status, source_date, families, _text = records[service]
        decision = {"status": status, "independent_families": list(families)}
        if source_date is not None:
            decision["source_date"] = source_date
        rows.append({"facility_id": campus, "as_of": AS_OF, "travel_minutes": travel[campus],
                     "services": {service: decision}})
    return rows


def _answer(service: str, urgency: str, budget: int, travel: dict) -> dict:
    request = {"service": service, "urgency": urgency, "as_of": AS_OF, "travel_metric": "travel_minutes",
               "travel_budget": budget, "candidates": _candidates(service, travel)}
    response = rank_campuses(**request)
    everyone = rank_campuses(**request, limit=None)
    eligible = [row["facility_id"] for row in everyone["ranked"]]
    shown = {row["facility_id"] for row in response["ranked"]}
    left_out = [{"facility_id": row["facility_id"], "travel": row["travel"], "kind": "ranked_lower", "reasons": [],
                 "row": row} for row in everyone["ranked"] if row["facility_id"] not in shown]
    rest = [row for row in request["candidates"] if row["facility_id"] not in eligible]
    near = [row for row in rest if row["travel_minutes"] <= budget]
    if near:
        # The ranker reports its reasons only when nothing qualifies, so ask it about these alone.
        asked = rank_campuses(**{**request, "candidates": near}, limit=None)
        left_out += [{"facility_id": row["facility_id"], "travel": row["travel"], "kind": "unconfirmed",
                      "reasons": row["reasons"]} for row in asked["needs_confirmation"]]
    left_out += [{"facility_id": row["facility_id"], "travel": float(row["travel_minutes"]), "kind": "too_far",
                  "reasons": []} for row in sorted(rest, key=lambda r: r["travel_minutes"])
                 if row["travel_minutes"] > budget]
    return {"request": request, "response": response, "eligible": len(eligible), "left_out": left_out}


def bundle() -> dict:
    scenario = json.loads(FIXTURE.read_text(encoding="utf-8"))
    travel = {origin["id"]: origin["travel_minutes"] for origin in scenario["origins"]}
    answers = {key(service, place, urgency): _answer(service, urgency, budget, travel[place])
               for service, _ in SERVICES for place, _ in PLACES for urgency, _, budget in URGENCIES}
    records = {f"{campus}|{service}": {"text": text, "status": status, "source_date": source_date,
                                       "sources": len(families)}
               for campus, by_service in RECORDS.items()
               for service, (status, source_date, families, text) in by_service.items()}
    return {
        "synthetic": True,
        "area": scenario["area"],
        "as_of": AS_OF,
        "services": [{"id": i, "name": n} for i, n in SERVICES],
        "urgencies": [{"id": i, "name": n, "travel_budget": b} for i, n, b in URGENCIES],
        "places": [{"id": i, "name": n} for i, n in PLACES],
        "campuses": {campus: {"name": f"Campus {campus}"} for campus in RECORDS},
        "records": records,
        "examples": [{"label": label, "service": s, "place": p, "urgency": u} for label, s, p, u in EXAMPLES],
        "answers": answers,
    }


def stable(value):
    """The same value with every fraction rounded to nine decimal places.

    Python 3.12 changed how `sum` adds fractions, so the ranker's scores differ in their last digit
    or two between Python versions (by about 1e-14). Nine places is far finer than anything the page
    shows and coarse enough that every supported Python writes the same file. Whole numbers, text,
    order and structure are untouched.
    """
    if isinstance(value, float):
        return round(value, DECIMALS)
    if isinstance(value, dict):
        return {name: stable(item) for name, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [stable(item) for item in value]
    return value


def render() -> str:
    body = json.dumps(stable(bundle()), ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    return f"{HEADER}window.CARE_ANSWERS = {body};\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.storm_ui.build_ask", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Compare with the committed file and change nothing")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"OUT OF DATE: {TARGET}", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({len(text.encode('utf-8'))} bytes, {len(bundle()['answers'])} answers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
